type Locale = "zh-CN" | "en";
type Key = keyof typeof zh;
interface I18nValue { locale: Locale; setLocale: (locale: Locale) => void; t: (key: Key) => string }
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => (localStorage.getItem("locale") === "en" ? "en" : "zh-CN"));
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale(next) { localStorage.setItem("locale", next); setLocaleState(next); },
    t(key) { return (locale === "en" ? en : zh)[key]; },
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider 缺失");
  return value;
}
